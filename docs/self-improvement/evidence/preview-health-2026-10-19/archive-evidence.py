from pathlib import Path
import hashlib,json,shutil,subprocess
ROOT=Path(__file__).resolve().parents[2]
OUT=Path(__file__).resolve().parent
DEST=ROOT/'docs/self-improvement/evidence/preview-health-2026-10-19'
DEST.mkdir(parents=True,exist_ok=True)
secrets=[]
for base in (OUT/'live',ROOT/'data/product-workbench'):
 for relative in ('operator-approval.key','previews/secret'):
  path=base/relative
  if path.exists():
   value=path.read_bytes().strip()
   if len(value)>=16:secrets.append(value)
manifest={}
def save(source,target):
 content=source.read_bytes()
 if any(secret in content for secret in secrets):raise RuntimeError('Credential value found in '+str(source))
 dest=DEST/target;dest.parent.mkdir(parents=True,exist_ok=True);dest.write_bytes(content)
 assert dest.read_bytes()==content
 manifest[str(target)]={'bytes':len(content),'sha256':hashlib.sha256(content).hexdigest()}
for path in sorted(OUT.rglob('*')):
 if not path.is_file():continue
 relative=path.relative_to(OUT)
 if relative.parts[0]=='live' or any(p in ('.git','__pycache__') for p in relative.parts) or path.name.endswith('.pyc'):continue
 save(path,relative)
for path in sorted((OUT/'live').rglob('*')):
 if not path.is_file():continue
 relative=path.relative_to(OUT/'live')
 if any(p in ('.git','__pycache__') for p in relative.parts) or path.name.endswith(('.pyc','-journal','-wal','-shm')):continue
 if str(relative) in ('operator-approval.key','previews/secret'):continue
 save(path,Path('fixture')/relative)
(DEST/'manifest.json').write_text(json.dumps(manifest,ensure_ascii=False,indent=2)+'\n')
report={'files':len(manifest),'total_bytes':sum(f['bytes'] for f in manifest.values()),'all_original_bytes_verified':True,'credential_value_matches':0,'excluded':'Private operator/preview credentials, transient SQLite journals, Git administrative files (full bundle retained), and generated bytecode only. Source files and execution logs remain complete.'}
(DEST/'archive-verification.json').write_text(json.dumps(report,ensure_ascii=False,indent=2)+'\n')
print(json.dumps(report))
