-- 核心表结构（Oracle）
CREATE TABLE OA_DEPT (
  ID NUMBER(19) PRIMARY KEY,
  DEPT_NAME VARCHAR2(100) NOT NULL,
  PARENT_ID NUMBER(19)
);

CREATE TABLE OA_USER (
  ID VARCHAR2(32) PRIMARY KEY,   -- 工号
  NAME VARCHAR2(50) NOT NULL,
  DEPT_ID NUMBER(19),
  STATUS VARCHAR2(10)            -- ACTIVE / DISABLED
);

CREATE TABLE OA_LEAVE (
  ID NUMBER(19) PRIMARY KEY,
  APPLICANT VARCHAR2(32),
  DEPT_ID NUMBER(19),
  DAYS NUMBER(3),
  REASON VARCHAR2(500),
  START_DATE DATE,
  STATUS VARCHAR2(16),           -- SUBMITTED / APPROVED / REJECTED / EXPIRED
  APPROVER VARCHAR2(32),
  APPROVED_AT DATE,
  CREATED DATE
);

CREATE TABLE OA_EXPENSE (
  ID NUMBER(19) PRIMARY KEY,
  USER_ID VARCHAR2(32),
  DEPT_ID NUMBER(19),
  AMOUNT NUMBER(12,2),
  CATEGORY VARCHAR2(20),         -- 差旅/招待/办公
  STATUS VARCHAR2(16),           -- SUBMITTED / AUDITED / REJECTED / PAID
  AUDITOR VARCHAR2(32),
  AUDITED_AT DATE,
  CASHIER VARCHAR2(32),
  PAID_AT DATE,
  CREATED DATE
);

CREATE TABLE OA_BUDGET (
  DEPT_ID NUMBER(19),
  MONTH CHAR(6),
  TOTAL NUMBER(14,2),
  FROZEN NUMBER(14,2) DEFAULT 0,
  USED NUMBER(14,2) DEFAULT 0
);

CREATE TABLE OA_APPROVAL_LOG (
  BILL_ID NUMBER(19),
  OPERATOR VARCHAR2(32),
  ACTION VARCHAR2(20),
  COMMENTS VARCHAR2(500),
  CREATED DATE
);
