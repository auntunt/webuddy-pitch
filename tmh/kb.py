def parse_page(text: str) -> dict:
    meta, body = {}, text
    if text.startswith("---\n"):
        end = text.find("\n---\n", 4)
        if end > 0:
            for line in text[4:end].splitlines():
                k, _, v = line.partition(":")
                if k.strip():
                    meta[k.strip()] = v.strip()
            body = text[end + 5:]
    else:  # notes written before the knowledge base existed: "状态：待确认" line
        sm = re.search(r"^状态[:：]\s*(\S+)", text, re.M)
        if sm:
            meta["status"] = sm.group(1)
            body = text[:sm.start()] + text[sm.end():].lstrip("\n")
    facts = FACTS_RX.search(body)
    understanding = FACTS_RX.sub("", body)
    title = re.search(r"^#\s+(.+)$", understanding, re.M)
    if title and "title" not in meta:
        meta["title"] = title.group(1).strip()
    understanding = re.sub(r"^#\s+.+\n+", "", understanding.lstrip("\n"), count=1) if title else understanding
    return {"meta": meta, "facts": facts.group(0) if facts else "", "body": understanding.strip("\n")}


def sections_of(body: str) -> dict:
    out, cur = {}, None
    for line in body.splitlines():
        h = re.match(r"^##\s+(.+?)\s*$", line)
        if h:
            cur = h.group(1)
            out[cur] = []
        elif cur:
            out[cur].append(line)
    return {k: "\n".join(v).strip() for k, v in out.items()}


def render_page(pid: str, meta: dict, facts: str, body: str) -> str:
    lines = ["---"]
    for k in ("id", "title", "summary", "status", "updated", "commit"):
        if meta.get(k):
            lines.append("%s: %s" % (k, str(meta[k]).replace("\n", " ")))
    lines.append("---")
    title = meta.get("title") or pid
    return "\n".join(lines) + "\n# %s\n\n%s\n%s\n" % (title, facts.rstrip("\n") + "\n" if facts else "", body.rstrip("\n") + "\n" if body else "")


def skeleton(kind: str) -> str:
    out = []
    for s in SECTIONS[kind]:
        out.append("## %s\n（%s）\n" % (s, HINTS[kind][s]))
    return "\n".join(out)


