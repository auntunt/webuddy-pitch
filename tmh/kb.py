# ---- paths & registry -------------------------------------------------------
def kdir(root: Path) -> Path:
    return tmh_dir(root) / "knowledge"


def page_path(root: Path, pid: str) -> Path:
    k = kdir(root)
    if pid == "index":
        return k / "index.md"
    kind, _, name = pid.partition(":")
    safe = re.sub(r"[^\w.一-鿿-]+", "_", name.strip("/").strip(".") or "root")
    return k / {"dom": "domains", "flow": "flows", "tbl": "entities", "mod": "modules"}[kind] / (safe + ".md")


def page_kind(pid: str) -> str:
    return "index" if pid == "index" else pid.split(":", 1)[0]


class _Lock:
    """Inter-process lock on the knowledge base. Uses kernel locks where available, so a
    lock file that cannot be deleted (restricted mounts) never blocks later runs."""

    def __init__(self, p: Path):
        self.p = p

    def __enter__(self):
        from .platform import filelock
        if filelock.available():
            self.fd = os.open(str(self.p), os.O_CREAT | os.O_WRONLY)
            try:
                for _ in range(1200):
                    try:
                        filelock.try_lock(self.fd)
                        return self
                    except BlockingIOError:
                        time.sleep(0.05)
                raise TimeoutError("知识库被占用：%s" % self.p)
            except BaseException:
                # __exit__ is not called when acquisition fails or is interrupted.
                # Only contention is retryable; preserve I/O errors from the backend.
                os.close(self.fd)
                raise
        for _ in range(200):
            try:
                self.fd = os.open(str(self.p), os.O_CREAT | os.O_EXCL | os.O_WRONLY)
                self.excl = True
                return self
            except FileExistsError:
                try:
                    if time.time() - self.p.stat().st_mtime > 60:
                        self.p.unlink()
                except OSError:
                    pass
                time.sleep(0.05)
        raise TimeoutError("知识库被占用：%s" % self.p)

    def __exit__(self, *a):
        os.close(self.fd)
        if getattr(self, "excl", False):
            try:
                self.p.unlink()
            except OSError:
                pass


def _reg_path(root: Path) -> Path:
    return kdir(root) / ".pages.json"


def load_registry(root: Path) -> dict:
    p = _reg_path(root)
    if p.exists():
        try:
            reg = json.loads(p.read_text(encoding="utf-8"))
            if isinstance(reg, dict):
                for pid, record in reg.items():
                    if not isinstance(record, dict) or "learning" not in record:
                        continue
                    try:
                        text = page_path(root, pid).read_bytes().decode("utf-8")
                    except (OSError, UnicodeError, KeyError):
                        text = None
                    status = confirmation_status(record, text)
                    if status != record.get("status"):
                        record["status"] = status
                        if status == "需更新":
                            record["stale"] = True
            return reg
        except ValueError:
            pass
    return {}


def confirmation_status(record: dict, text: str | None) -> str:
    """Learning confirmations apply only to exact bytes; reads never recover writes."""
    state = record.get("learning")
    status = record.get("status", "")
    if not isinstance(state, dict):
        return STATUS_DRAFT if "learning" in record else status
    if state.get("pending"):
        return STATUS_DRAFT
    expected = state.get("confirmed_sha256")
    if status == STATUS_OK:
        if text is None or not expected or hashlib.sha256(text.encode("utf-8")).hexdigest() != expected:
            return "需更新"
    return status


def _atomic_text(path: Path, text: str) -> None:
    """Strict atomic publication: never fall back to overwriting the destination."""
    fd, name = tempfile.mkstemp(prefix="." + path.name + ".", suffix=".tmp", dir=path.parent)
    tmp = Path(name)
    try:
        with os.fdopen(fd, "w", encoding="utf-8", newline="") as output:
            output.write(text)
            output.flush()
            os.fsync(output.fileno())
        if path.exists():
            os.chmod(tmp, path.stat().st_mode & 0o777)
        os.replace(tmp, path)
    finally:
        tmp.unlink(missing_ok=True)


def save_registry(root: Path, reg: dict, *, _atomic: bool = False) -> None:
    p = _reg_path(root)
    p.parent.mkdir(parents=True, exist_ok=True)
    if _atomic:
        _atomic_text(p, json.dumps(dict(sorted(reg.items())), ensure_ascii=False, indent=1))
        return
    tmp = p.with_suffix(".tmp")
    tmp.write_text(json.dumps(dict(sorted(reg.items())), ensure_ascii=False, indent=1), encoding="utf-8")
    replace_file(tmp, p)


