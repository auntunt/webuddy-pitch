def flow_score(n: dict) -> int:
    d = n["data"]
    crud = d.get("crud", {})
    writes = sum(1 for ops in crud.values() if set(ops) & set("CUDP"))
    return 3 * writes + 3 * d.get("states", 0) + d.get("rules", 0) + 2 * len(d.get("effects", [])) + (1 if d.get("entry_kind") != "接口" else 0)


def scope(g: Graph, cfg: dict) -> dict:
    """Pages the full analysis covers: id -> reason. The rest stay fact-only until a task needs them."""
    kcfg = cfg.get("kb", {})
    per_dom = int(kcfg.get("max_flows_per_domain", 25))
    out = {"index": "总览"}
    flows = g.nodes("flow")
    by_dom = defaultdict(list)
    for f in flows:
        by_dom[f["domain"]].append(f)
    for d, fl in by_dom.items():
        fl.sort(key=lambda n: -flow_score(n))
        for f in fl[:per_dom]:
            if kcfg.get("all_flows") or flow_score(f) > 0:
                out[f["id"]] = "核心业务流"
    written = set()
    for f in flows:
        for t, ops in f["data"].get("crud", {}).items():
            if set(ops) & set("CUD"):
                written.add("tbl:" + t)
    for t in g.nodes("tbl"):
        if t["id"] in written or (t["data"].get("ddl") and t["data"].get("kind_") == "table" and g.inn(t["id"], "uses")):
            out[t["id"]] = "被业务写入的表"
    for d in g.nodes("dom"):
        out[d["id"]] = "业务域"
    mods = g.nodes("mod")
    for m in mods:
        if m["data"].get("files"):
            out[m["id"]] = "代码模块"
    return out


