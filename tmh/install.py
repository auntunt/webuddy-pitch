"""Install the harness into a target repository for Claude Code and/or Codex."""
from __future__ import annotations

import json
import shutil
from pathlib import Path

from . import config as cfgmod
from . import resources

PKG = Path(__file__).resolve().parent
HOME = resources.root()
BEGIN, END = "<!-- tmh:begin -->", "<!-- tmh:end -->"
HOOK = 'python3 "$CLAUDE_PROJECT_DIR/.tmh/tool/tmh.py" hook %s'

CLAUDE_HOOKS = {
    "PreToolUse": [
        {"matcher": "Edit|Write|MultiEdit|NotebookEdit", "hooks": [{"type": "command", "command": HOOK % "pre-edit", "timeout": 30}]},
        {"matcher": "Bash", "hooks": [{"type": "command", "command": HOOK % "pre-bash", "timeout": 30}]},
    ],
    "PostToolUse": [
        # Logs every tool call for the report's 分析过程, and checks edited files.
        {"matcher": "*", "hooks": [{"type": "command", "command": HOOK % "agent-post", "timeout": 60}]},
    ],
    "Stop": [
        {"hooks": [{"type": "command", "command": HOOK % "stop", "timeout": 60}]},
    ],
}


def _copytree(src: Path, dst: Path) -> None:
    if src.resolve() == dst.resolve():
        return
    if dst.exists():
        shutil.rmtree(dst)
    shutil.copytree(src, dst, ignore=shutil.ignore_patterns("__pycache__", "*.pyc"))


def _upsert_block(path: Path, block: str, header: str = "") -> None:
    wrapped = "%s\n%s\n%s" % (BEGIN, block.strip(), END)
    if path.exists():
        text = path.read_text(encoding="utf-8")
        if BEGIN in text and END in text:
            pre, rest = text.split(BEGIN, 1)
            post = rest.split(END, 1)[1]
            text = pre + wrapped + post
        else:
            text = text.rstrip() + "\n\n" + wrapped + "\n"
    else:
        text = (header + "\n\n" if header else "") + wrapped + "\n"
    path.write_text(text, encoding="utf-8")


# Codex hooks (.codex/hooks.json). Codex has no $CLAUDE_PROJECT_DIR, so resolve the
# repository root with git. Event names and handler shape follow the Codex hooks docs.
CODEX_HOOK = 'python3 "$(git rev-parse --show-toplevel 2>/dev/null || pwd)/.tmh/tool/tmh.py" hook %s'
CODEX_HOOKS = {
    "PreToolUse": [{"matcher": ".*", "hooks": [{"type": "command", "command": CODEX_HOOK % "agent-pre", "timeout": 30}]}],
    "PostToolUse": [{"matcher": ".*", "hooks": [{"type": "command", "command": CODEX_HOOK % "agent-post", "timeout": 60}]}],
    "Stop": [{"hooks": [{"type": "command", "command": CODEX_HOOK % "stop", "timeout": 60}]}],
}


def _merge_codex_hooks(path: Path) -> None:
    data = {}
    if path.exists():
        data = json.loads(path.read_text(encoding="utf-8") or "{}")
    hooks = data.setdefault("hooks", {})
    for event, entries in CODEX_HOOKS.items():
        cur = [e for e in hooks.get(event, []) if ".tmh/tool/tmh.py" not in json.dumps(e)]
        hooks[event] = cur + entries
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(data, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")


def _codex_agent(md_path: Path) -> str:
    """Convert a Claude subagent (Markdown + front matter) into a Codex custom agent (TOML)."""
    text = md_path.read_text(encoding="utf-8")
    fm, body = text.split("---", 2)[1], text.split("---", 2)[2].strip()
    meta = dict(l.split(":", 1) for l in fm.strip().splitlines() if ":" in l)
    q = lambda s: json.dumps(s.strip(), ensure_ascii=False)
    return "name = %s\ndescription = %s\ndeveloper_instructions = %s\n" % (q(meta["name"]), q(meta["description"]), q(body))


def _merge_hooks(settings_path: Path) -> None:
    data = {}
    if settings_path.exists():
        data = json.loads(settings_path.read_text(encoding="utf-8") or "{}")
    allow = data.setdefault("permissions", {}).setdefault("allow", [])
    for rule in ("Bash(python3 .tmh/tool/tmh.py:*)", "Read(.tmh/**)", "mcp__tmh"):
        if rule not in allow:
            allow.append(rule)
    enabled = data.setdefault("enabledMcpjsonServers", [])
    if "tmh" not in enabled:
        enabled.append("tmh")
    hooks = data.setdefault("hooks", {})
    for event, entries in CLAUDE_HOOKS.items():
        cur = [e for e in hooks.get(event, []) if ".tmh/tool/tmh.py" not in json.dumps(e)]
        hooks[event] = cur + entries
    settings_path.parent.mkdir(parents=True, exist_ok=True)
    settings_path.write_text(json.dumps(data, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")


# MCP server entry (tmh mcp). The shell wrapper finds the repo root the same way the Codex hooks do.
MCP_SHELL = 'cd "$(git rev-parse --show-toplevel 2>/dev/null || pwd)" && exec python3 .tmh/tool/tmh.py mcp'
TOML_BEGIN, TOML_END = "# tmh:begin (generated by tmh install; rerun to refresh)", "# tmh:end"


def _write_claude_mcp(repo: Path) -> None:
    p = repo / ".mcp.json"
    data = json.loads(p.read_text(encoding="utf-8") or "{}") if p.exists() else {}
    data.setdefault("mcpServers", {})["tmh"] = {"type": "stdio", "command": "sh", "args": ["-c", MCP_SHELL]}
    p.write_text(json.dumps(data, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")


def _write_codex_mcp(repo: Path) -> None:
    """[mcp_servers.tmh] in .codex/config.toml. Codex passes only a few env vars to MCP servers,
    so the credential variable names configured in integrations are forwarded via env_vars."""
    from .integrations import all_env_names
    q = lambda v: json.dumps(v, ensure_ascii=False)
    envs = all_env_names(repo)
    block = "\n".join([TOML_BEGIN, "[mcp_servers.tmh]", 'command = "sh"', "args = [%s, %s]" % (q("-c"), q(MCP_SHELL)),
                       "env_vars = [%s]" % ", ".join(q(e) for e in envs), "startup_timeout_sec = 20", "tool_timeout_sec = 180", TOML_END])
    p = repo / ".codex" / "config.toml"
    p.parent.mkdir(parents=True, exist_ok=True)
    text = p.read_text(encoding="utf-8") if p.exists() else ""
    if TOML_BEGIN in text and TOML_END in text:
        pre, rest = text.split(TOML_BEGIN, 1)
        text = pre + block + rest.split(TOML_END, 1)[1]
    else:
        text = (text.rstrip() + "\n\n" if text.strip() else "") + block + "\n"
    p.write_text(text, encoding="utf-8")


def refresh_mcp(repo: Path) -> None:
    """Called after `tmh int add/remove` so Codex forwards the right credential variables."""
    if (repo / ".codex" / "config.toml").exists() and TOML_BEGIN in (repo / ".codex" / "config.toml").read_text(encoding="utf-8"):
        _write_codex_mcp(repo)


def install(repo: Path, engines: list[str], git_hook: bool = False) -> list[str]:
    repo = repo.resolve()
    assets = list(resources.files(HOME))
    done = []
    x = cfgmod.tmh_dir(repo)
    x.mkdir(parents=True, exist_ok=True)
    # 1. Vendored tool: the repo stays self-contained and works offline.
    tool = x / "tool"
    tool.mkdir(exist_ok=True)
    _copytree(PKG, tool / "tmh")
    # Keep the vendored command self-contained, including reinstallation and
    # offline-pack. Wheel assets and checkout assets have the same layout.
    for source, relative in assets:
        target = tool / "tmh" / "_resources" / relative
        if source.resolve() != target.resolve():
            target.parent.mkdir(parents=True, exist_ok=True)
            shutil.copyfile(source, target)
    (tool / "tmh.py").write_text(
        "import os, sys\nsys.dont_write_bytecode = True\nsys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))\n"
        "from tmh.cli import main\nsys.exit(main())\n", encoding="utf-8")
    done.append(".tmh/tool/ (内置工具，python3 .tmh/tool/tmh.py)")
    # 2. Knowledge base and project-knowledge skeleton.
    _copytree(HOME / "kb", x / "kb")
    done.append(".tmh/kb/ (信创知识库)")
    kdir = x / "knowledge"
    kdir.mkdir(exist_ok=True)
    readme = kdir / "README.md"
    if not readme.exists():
        shutil.copy(HOME / "templates" / "knowledge-README.md", readme)
    if not (x / "config.json").exists():
        cfgmod.save(repo, cfgmod.load(repo))
    gi = x / ".gitignore"
    lines = gi.read_text(encoding="utf-8").split() if gi.exists() else []
    for ign in ("reports/", "stale-files.txt", "scan.json", "__pycache__/", "cache/", "map.json", "flows.json"):
        if ign not in lines:
            lines.append(ign)
    gi.write_text("\n".join(lines) + "\n", encoding="utf-8")
    # 3. Agent entry files.
    agents_block = (HOME / "templates" / "AGENTS.block.md").read_text(encoding="utf-8")
    (x / "docs").mkdir(exist_ok=True)
    shutil.copy(HOME / "docs" / "agent-commands.md", x / "docs" / "agent-commands.md")
    _upsert_block(repo / "AGENTS.md", agents_block, "# AGENTS.md")
    done.append("AGENTS.md（插入 tmh 区块，保留原有内容）")
    skills = sorted(p for p in (HOME / "skills").iterdir() if (p / "SKILL.md").exists())
    if "claude" in engines:
        _upsert_block(repo / "CLAUDE.md", "@AGENTS.md\n\n" + (HOME / "templates" / "CLAUDE.block.md").read_text(encoding="utf-8"), "# CLAUDE.md")
        for s in skills:
            _copytree(s, repo / ".claude" / "skills" / s.name)
        for a in sorted((HOME / "agents").glob("*.md")):
            (repo / ".claude" / "agents").mkdir(parents=True, exist_ok=True)
            shutil.copy(a, repo / ".claude" / "agents" / a.name)
        _merge_hooks(repo / ".claude" / "settings.json")
        _write_claude_mcp(repo)
        done.append("CLAUDE.md、.claude/skills (%d)、.claude/agents、.claude/settings.json 钩子、.mcp.json（tmh MCP 服务）" % len(skills))
    if "codex" in engines:
        for s in skills:
            _copytree(s, repo / ".agents" / "skills" / s.name)
        done.append(".agents/skills (%d)（Codex 技能目录）" % len(skills))
        for a in sorted((HOME / "agents").glob("*.md")):
            (repo / ".codex" / "agents").mkdir(parents=True, exist_ok=True)
            (repo / ".codex" / "agents" / (a.stem + ".toml")).write_text(_codex_agent(a), encoding="utf-8")
        _merge_codex_hooks(repo / ".codex" / "hooks.json")
        _write_codex_mcp(repo)
        done.append(".codex/agents（子代理）、.codex/hooks.json（钩子）、.codex/config.toml（tmh MCP 服务）")
    # 4. Ops-tool plugin folder with an example (files starting with _ are not loaded).
    pdir = x / "integrations"
    pdir.mkdir(exist_ok=True)
    shutil.copy(HOME / "templates" / "integration_plugin_example.py", pdir / "_example.py")
    if git_hook and (repo / ".git").is_dir():
        hp = repo / ".git" / "hooks" / "pre-commit"
        hp.write_text('#!/bin/sh\nexec python3 "$(git rev-parse --show-toplevel)/.tmh/tool/tmh.py" hook pre-commit\n', encoding="utf-8")
        hp.chmod(0o755)
        done.append(".git/hooks/pre-commit（保护基线测试）")
    return done
